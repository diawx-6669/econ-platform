  function navigate(state) {
    if (state.view === "lesson") {
      renderSidebar(state.lessonId);
      renderLesson(state.lessonId);
    } else if (state.view === "profile") {
      renderSidebar(null, true);
      renderProfile();
    } else if (state.view === "tools") {
      renderSidebar(null, false, null, true);
      renderToolsOverview();
    } else if (state.view === "tool") {
      renderSidebar(null, false, state.toolId, false);
      renderTool(state.toolId);
    } else if (state.view === "mathquiz") {
      renderSidebar(null);
      renderMathQuiz(state.courseId);
    } else {
      renderSidebar(null);
      renderOverview();
    }
    updateStreak();
    window.scrollTo({ top: 0, behavior: "smooth" });
  }

  // initial route
  if (progress.lastVisited && LESSON_INDEX[progress.lastVisited]) {
    renderSidebar(null);
  }
